const fs = require("fs");
const path = require("path");
const prettier = require("prettier");

const projectRoot = path.resolve(__dirname, "..");
const appDirectory = path.join(projectRoot, "src", "app");
const validTopicFilename = /^[a-z0-9]+(?:-[a-z0-9]+)*\.tsx$/;

function getTopicDirectories() {
  return fs
    .readdirSync(appDirectory, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => ({
      sectionName: entry.name,
      directory: path.join(appDirectory, entry.name, "topics"),
    }))
    .filter(({ directory }) => fs.existsSync(directory));
}

function getTopicFiles(topicsDirectory) {
  const topicFiles = fs
    .readdirSync(topicsDirectory, { withFileTypes: true })
    .filter((entry) => entry.isFile() && entry.name.endsWith(".tsx"))
    .map((entry) => entry.name)
    .sort();

  if (topicFiles.length === 0) {
    throw new Error(`Topic directory is empty: ${topicsDirectory}`);
  }

  for (const fileName of topicFiles) {
    if (!validTopicFilename.test(fileName)) {
      throw new Error(
        `Invalid topic filename "${fileName}". Use lowercase kebab-case names ending in .tsx.`,
      );
    }

    const source = fs.readFileSync(
      path.join(topicsDirectory, fileName),
      "utf8",
    );
    if (!/export\s+const\s+metadata\s*=/.test(source)) {
      throw new Error(`Topic "${fileName}" must export a metadata constant.`);
    }
    if (!/export\s+default\s+(function|\(?)/.test(source)) {
      throw new Error(
        `Topic "${fileName}" must have a default component export.`,
      );
    }
  }

  return topicFiles;
}

function generateRegistry(topicFiles) {
  const imports = topicFiles
    .map((fileName, index) => {
      const modulePath = `./topics/${fileName.replace(/\.tsx$/, "")}`;
      return `import Topic${index}, { metadata as metadata${index} } from "${modulePath}";`;
    })
    .join("\n");

  const entries = topicFiles
    .map(
      (_, index) =>
        `  { ...metadata${index}, Component: Topic${index} } satisfies Topic,`,
    )
    .join("\n");

  return `// This file is generated by scripts/generate-topic-registries.cjs. Do not edit manually.\nimport type { Topic } from "@/components/topics/types";\n\n${imports}\n\nexport const topics = [\n${entries}\n].sort((left, right) => left.order - right.order || left.title.localeCompare(right.title));\n`;
}

async function writeRegistries() {
  const topicDirectories = getTopicDirectories();

  if (topicDirectories.length === 0) {
    throw new Error("No topic directories were found in src/app.");
  }

  await Promise.all(
    topicDirectories.map(async ({ sectionName, directory }) => {
      const topicFiles = getTopicFiles(directory);
      const outputPath = path.join(
        appDirectory,
        sectionName,
        "topics.generated.tsx",
      );
      const registry = generateRegistry(topicFiles);
      const prettierConfig = await prettier.resolveConfig(outputPath);
      const formatted = await prettier.format(registry, {
        ...prettierConfig,
        filepath: outputPath,
      });

      fs.writeFileSync(outputPath, formatted);
    }),
  );
}

void writeRegistries().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
