const fs = require("fs");
const path = require("path");
const prettier = require("prettier");

const projectRoot = path.resolve(__dirname, "..");
const topicsDirectory = path.join(
  projectRoot,
  "src",
  "app",
  "adaptation",
  "topics",
);
const outputPath = path.join(
  projectRoot,
  "src",
  "app",
  "adaptation",
  "topics.generated.tsx",
);
const validTopicFilename = /^[a-z0-9]+(?:-[a-z0-9]+)*\.tsx$/;

if (!fs.existsSync(topicsDirectory)) {
  throw new Error(`Topic directory does not exist: ${topicsDirectory}`);
}

const topicFiles = fs
  .readdirSync(topicsDirectory, { withFileTypes: true })
  .filter((entry) => entry.isFile() && entry.name.endsWith(".tsx"))
  .map((entry) => entry.name)
  .sort();

for (const fileName of topicFiles) {
  if (!validTopicFilename.test(fileName)) {
    throw new Error(
      `Invalid topic filename "${fileName}". Use lowercase kebab-case names ending in .tsx.`,
    );
  }

  const source = fs.readFileSync(path.join(topicsDirectory, fileName), "utf8");
  if (!/export\s+const\s+metadata\s*=/.test(source)) {
    throw new Error(`Topic "${fileName}" must export a metadata constant.`);
  }
  if (!/export\s+default\s+(function|\(?)/.test(source)) {
    throw new Error(
      `Topic "${fileName}" must have a default component export.`,
    );
  }
}

const imports = topicFiles
  .map((fileName, index) => {
    const modulePath = `./topics/${fileName.replace(/\.tsx$/, "")}`;
    return `import Topic${index}, { metadata as metadata${index} } from "${modulePath}";`;
  })
  .join("\n");

const entries = topicFiles
  .map(
    (_, index) =>
      `  { ...metadata${index}, Component: Topic${index} } satisfies AdaptationTopic,`,
  )
  .join("\n");

const generated = `// This file is generated by scripts/generate-adaptation-topics.cjs. Do not edit manually.\nimport type { ComponentType } from "react";\n\n${imports}\n\nexport type AdaptationTopicMetadata = {\n  slug: string;\n  title: string;\n  description: string;\n  order: number;\n};\n\nexport type AdaptationTopic = AdaptationTopicMetadata & {\n  Component: ComponentType;\n};\n\nexport const adaptationTopics = [\n${entries}\n].sort((left, right) => left.order - right.order || left.title.localeCompare(right.title));\n`;

async function writeRegistry() {
  const formatted = await prettier.format(generated, { filepath: outputPath });
  fs.writeFileSync(outputPath, formatted);
}

void writeRegistry().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
